# UTILITY FUNCTIONS
def load_model_information(file_path: Path) -> dict:
    """
    Load run information generated by the previous MLflow stage.
    """

    if not file_path.exists():
        raise FileNotFoundError(
            f"Run information file not found: {file_path}"
        )

    with open(file_path, "r") as file:
        return json.load(file)


def get_model_artifact(client: MlflowClient, run_id: str, model_name: str):
    """
    Check whether the expected model artifact exists inside the MLflow run.

    Returns the correct artifact path.
    """

    logger.info(f"Checking MLflow artifacts for run: {run_id}")

    artifacts = client.list_artifacts(run_id)
    artifact_paths = [artifact.path for artifact in artifacts]

    logger.info(f"Artifacts found in run: {artifact_paths}")

    # First try the model name from run_information.json
    if model_name in artifact_paths:
        logger.info(f"Model artifact '{model_name}' found.")
        return model_name

    # Fallback to "model"
    if "model" in artifact_paths:
        logger.warning(f"Artifact '{model_name}' was not found.")
        logger.info("Using fallback model artifact: model")
        return "model"

    # Nothing found
    raise RuntimeError(
        "\nModel artifact was not found.\n"
        f"Expected artifact: {model_name}\n"
        f"Available artifacts: {artifact_paths}\n"
        f"Run ID: {run_id}"
    )


if __name__ == "__main__":
    logger.info("=" * 70)
    logger.info("STARTING MODEL REGISTRATION")
    logger.info("=" * 70)

    # Project root
    root_path = Path.cwd()

    logger.info(f"Current working directory: {root_path}")

    # Load run_information.json
    run_info_path = root_path / "run_information.json"
    run_info = load_model_information(run_info_path)

    logger.info(f"Run information loaded from: {run_info_path}")

    # Extract information
    run_id = run_info["run_id"]
    model_name = run_info.get("model_name","model")

    logger.info(f"Run ID: {run_id}")
    logger.info(f"Model name from run_information.json: {model_name}")

    # Create MLflow client
    client = MlflowClient(tracking_uri=tracking_uri)

    try:
        run = client.get_run(run_id)

        logger.info("Successfully connected to DagsHub MLflow.")
        logger.info(f"Run ID: {run.info.run_id}")
        logger.info(f"Run status: {run.info.status}")
        logger.info(f"Experiment ID: {run.info.experiment_id}")
    except Exception as e:
        logger.exception("Could not access the MLflow run.")

        raise RuntimeError(
            "\nCould not authenticate/connect to DagsHub MLflow.\n"
            "Check:\n"
            "1. DAGSHUB_TOKEN is correct\n"
            "2. DagsHub username is correct\n"
            "3. Repository name is correct\n"
            "4. Your DagsHub token has write access\n"
        ) from e


    # STEP 2 — CHECK MODEL ARTIFACT
    logger.info("=" * 70)
    logger.info("STEP 2: CHECKING MODEL ARTIFACT")
    logger.info("=" * 70)

    model_artifact = get_model_artifact(client=client,run_id=run_id,model_name=model_name,)
    logger.info(f"Using model artifact: {model_artifact}")

    # STEP 3 — BUILD MODEL URI
    model_uri = (f"runs:/{run_id}/{model_artifact}")
    logger.info(f"Model URI: {model_uri}")

    # STEP 4 — REGISTER MODEL
    logger.info("=" * 70)
    logger.info("STEP 3: REGISTERING MODEL")
    logger.info("=" * 70)

    try:
        model_version = mlflow.register_model(model_uri=model_uri,name=model_artifact,)
    except Exception as e:
        logger.exception("Model registration failed.")

        raise RuntimeError(
            "\nMLflow model registration failed.\n"
            f"Model URI: {model_uri}\n"
            f"Model name: {model_artifact}\n"
            "Check DagsHub repository write permissions and token."
        ) from e

    logger.info("Model successfully registered.")
    logger.info(f"Registered model name: {model_version.name}")
    logger.info(f"Model version: {model_version.version}")

    # STEP 5 — MOVE MODEL TO STAGING
    logger.info("=" * 70)
    logger.info("STEP 4: MOVING MODEL TO STAGING")
    logger.info("=" * 70)

    try:
        client.transition_model_version_stage(name=model_version.name,version=model_version.version,stage="Staging",archive_existing_versions=False,)
        logger.info("Model successfully promoted to STAGING.")
    except Exception as e:
        logger.warning("Model was registered successfully, but moving it to Staging failed.")

        logger.warning(f"Staging error: {e}")
        logger.warning("Registration itself was successful.")

    # COMPLETE
    logger.info("=" * 70)
    logger.info("MODEL REGISTRATION PIPELINE COMPLETED")
    logger.info("=" * 70)

    logger.info(f"Model: {model_version.name}")
    logger.info(f"Version: {model_version.version}")
    logger.info(f"Run ID: {run_id}")
    logger.info(f"Model URI: {model_uri}")